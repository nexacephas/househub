import "./ReportDetails.css";

import {
  X,
  FileText,
  Calendar,
  User,
  FolderOpen,
  CircleCheck,
} from "lucide-react";

export default function ReportDetails({
  report,
  open,
  onClose,
}) {
  if (!open || !report) return null;

  return (
    <div className="report-details-overlay">

      <div className="report-details">

        <div className="report-details-header">

          <h2>Report Details</h2>

          <button onClick={onClose}>
            <X size={22} />
          </button>

        </div>

        <div className="report-detail-item">

          <FileText size={18} />

          <div>
            <label>Title</label>
            <p>{report.title}</p>
          </div>

        </div>

        <div className="report-detail-item">

          <FolderOpen size={18} />

          <div>
            <label>Type</label>
            <p>{report.type}</p>
          </div>

        </div>

        <div className="report-detail-item">

          <User size={18} />

          <div>
            <label>Generated By</label>
            <p>{report.generatedBy}</p>
          </div>

        </div>

        <div className="report-detail-item">

          <Calendar size={18} />

          <div>
            <label>Date</label>

            <p>
              {new Date(report.createdAt).toLocaleString()}
            </p>

          </div>

        </div>

        <div className="report-detail-item">

          <CircleCheck size={18} />

          <div>

            <label>Status</label>

            <p>{report.status}</p>

          </div>

        </div>

        <div className="report-description">

          <h3>Description</h3>

          <p>
            {report.description ||
              "No description provided."}
          </p>

        </div>

      </div>

    </div>
  );
}