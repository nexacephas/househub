import "./ReportFilters.css";

import { Search } from "lucide-react";

export default function ReportFilters({
  filters,
  setFilters,
}) {
  function handleChange(e) {
    const { name, value } = e.target;

    setFilters((prev) => ({
      ...prev,
      [name]: value,
    }));
  }

  return (
    <div className="report-filters">

      <div className="search-box">

        <Search size={18} />

        <input
          type="text"
          name="search"
          placeholder="Search reports..."
          value={filters.search}
          onChange={handleChange}
        />

      </div>

      <select
        name="type"
        value={filters.type}
        onChange={handleChange}
      >
        <option value="">
          All Types
        </option>

        <option value="Revenue">
          Revenue
        </option>

        <option value="Bookings">
          Bookings
        </option>

        <option value="Users">
          Users
        </option>

        <option value="Properties">
          Properties
        </option>

      </select>

      <select
        name="status"
        value={filters.status}
        onChange={handleChange}
      >
        <option value="">
          All Status
        </option>

        <option value="Generated">
          Generated
        </option>

        <option value="Scheduled">
          Scheduled
        </option>

        <option value="Failed">
          Failed
        </option>

      </select>

      <input
        type="date"
        name="date"
        value={filters.date}
        onChange={handleChange}
      />

      <select
        name="generatedBy"
        value={filters.generatedBy}
        onChange={handleChange}
      >
        <option value="">
          Generated By
        </option>

        <option value="Admin">
          Admin
        </option>

        <option value="System">
          System
        </option>

      </select>

    </div>
  );
}