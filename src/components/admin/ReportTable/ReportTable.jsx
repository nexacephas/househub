import "./ReportTable.css";

import {
  Eye,
  Download,
  Share2,
  Trash2,
  FileText,
} from "lucide-react";

export default function ReportTable({
  reports = [],
  loading,
  onSelect,
  onDelete,
}) {
  if (loading) {
    return (
      <div className="report-table-loading">
        Loading reports...
      </div>
    );
  }

  if (!reports.length) {
    return (
      <div className="report-table-loading">
        No reports found.
      </div>
    );
  }

  return (
    <div className="report-table-wrapper">

      <table className="report-table">

        <thead>

          <tr>

            <th>Report</th>

            <th>Type</th>

            <th>Generated By</th>

            <th>Date</th>

            <th>Format</th>

            <th>Status</th>

            <th>Actions</th>

          </tr>

        </thead>

        <tbody>

          {reports.map((report) => (

            <tr key={report._id}>

              <td>

                <div className="report-info">

                  <div className="report-icon">
                    <FileText size={22} />
                  </div>

                  <div>

                    <h4>{report.title}</h4>

                    <span>
                      {report.description || "System Report"}
                    </span>

                  </div>

                </div>

              </td>

              <td>{report.type}</td>

              <td>
                {report.generatedBy || "System"}
              </td>

              <td>
                {new Date(
                  report.createdAt
                ).toLocaleDateString()}
              </td>

              <td>{report.format}</td>

              <td>

                <span
                  className={`report-status ${(
                    report.status || ""
                  ).toLowerCase()}`}
                >
                  {report.status}
                </span>

              </td>

              <td>

                <div className="report-actions">

                  <button
                    className="view-btn"
                    onClick={() =>
                      onSelect(report)
                    }
                  >
                    <Eye size={18} />
                  </button>

                  <button className="download-btn">
                    <Download size={18} />
                  </button>

                  <button className="export-btn">
                    <Share2 size={18} />
                  </button>

                  <button
                    className="delete-btn"
                    onClick={() =>
                      onDelete(report)
                    }
                  >
                    <Trash2 size={18} />
                  </button>

                </div>

              </td>

            </tr>

          ))}

        </tbody>

      </table>

    </div>
  );
}